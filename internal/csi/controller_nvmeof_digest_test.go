// TestCreateVolume_NVMeoFDigestsNotRecorded verifies that CreateVolume keeps
// the digests out of the VolumeContext and the resolved record: they are
// read from the live PillarProtocol at each publish, so a recorded copy
// could only go stale.
func TestCreateVolume_NVMeoFDigestsNotRecorded(t *testing.T) {
	t.Parallel()
	env := newControllerTestEnv(t)
	ctx := context.Background()
	proto := &v1alpha1.PillarProtocol{}
	if err := env.srv.k8sClient.Get(ctx, ctrlKey(testProtocolName), proto); err != nil {
		t.Fatalf("get protocol: %v", err)
	}
	proto.Spec.Protocol.NVMeOFTCP.HdrDigest = true
	proto.Spec.Protocol.NVMeOFTCP.DataDigest = true
	if err := env.srv.k8sClient.Update(ctx, proto); err != nil {
		t.Fatalf("update protocol: %v", err)
	}

	resp, err := env.srv.CreateVolume(ctx, baseCreateVolumeRequest())
	if err != nil {
		t.Fatalf("CreateVolume: %v", err)
	}
	if got := digestKeys(resp.GetVolume().GetVolumeContext()); len(got) != 0 {
		t.Errorf("VolumeContext digest keys = %v, want none", got)
	}
	pvs, _, err := env.srv.loadPillarVolumeState(ctx, pillarVolumeStateNameFromVolumeID(resp.GetVolume().GetVolumeId()))
	if err != nil {
		t.Fatalf("load PillarVolumeState: %v", err)
	}
	n := pvs.Spec.Resolved.Protocol.NVMeOFTCP
	if n == nil || n.HdrDigest || n.DataDigest {
		t.Errorf("resolved nvmeofTcp = %+v, want digests cleared", n)
	}
}
