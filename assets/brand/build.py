def shapes(geometry, colors, classes: bool = False) -> str:
    out = []
    for part, x, y, w, h, r in geometry:
        cls = f' class="pc-{part}"' if classes else ""
        rx = f' rx="{r:g}"' if r else ""
        out.append(f'<rect{cls} x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}"{rx} fill="{colors[part]}"/>')
    return "".join(out)


def mark(x: float, y: float, size: float, colors=ON_DARK) -> str:
    """The 64-unit mark drawn size px tall with its origin at (x, y)."""
    return f'<g transform="translate({x:g} {y:g}) scale({size / 64:g})">{shapes(MARK, colors)}</g>'


# ---------------------------------------------------------------- helpers


def need(binary: str) -> str:
    path = shutil.which(binary)
    if not path:
        sys.exit(f"{binary} not found on PATH; run via `nix shell nixpkgs#resvg --command ...`")
    return path


def fetch_font(explicit: Path | None) -> Path:
    if explicit:
        return explicit
    cache = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "pillar-csi"
    path = cache / f"Archivo-{FONT_SHA256[:12]}.ttf"
    if not path.exists():
        cache.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(FONT_URL) as resp:
            data = resp.read()
        if hashlib.sha256(data).hexdigest() != FONT_SHA256:
            sys.exit(f"Archivo download from {FONT_URL} does not match the pinned SHA-256")
        path.write_bytes(data)
    return path


def font_args(font: Path) -> list[str]:
    return ["--skip-system-fonts", "--use-font-file", str(font)]


def text(x: float, y: float, s: str, size: float, fill: str, weight: int = 400,
         anchor: str = "start", stretch: str = "normal", spacing: float = 0) -> str:
    return (
        f'<text x="{x:g}" y="{y:g}" font-family="Archivo" font-size="{size:g}" '
        f'font-weight="{weight}" font-stretch="{stretch}" fill="{fill}" '
        f'text-anchor="{anchor}" letter-spacing="{spacing:g}">{escape(s)}</text>'
    )


def render(svg: str, out: Path, font: Path, width: int | None = None,
           height: int | None = None) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as fh:
        fh.write(svg)
        src = fh.name
    cmd = [need("resvg"), *font_args(font)]
    if width:
        cmd += ["-w", str(width)]
    if height:
        cmd += ["-h", str(height)]
    subprocess.run([*cmd, src, str(out)], check=True)
    Path(src).unlink()


def svg_doc(w: float, h: float, body: str, vb: str | None = None) -> str:
    return (
        f'<svg xmlns="{SVG_NS}" viewBox="{vb or f"0 0 {w:g} {h:g}"}" width="{w:g}" height="{h:g}" '
        f'role="img" aria-label="pillar-csi"><title>pillar-csi</title>\n'
        f"<!-- {GEN_NOTE} -->\n{body}\n</svg>\n"
    )


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


# ---------------------------------------------------------------- wordmark
#
# "pillar-csi" in Archivo Bold at width 125 (Expanded), tracking -0.01em,
# outlined by usvg. wordmark_geometry returns the raw path (baseline at 0)
# plus its bounds, so each lockup can place it exactly.
WORD_SIZE = 36
WORD_GAP = 16
WORD_TRACKING = -0.01  # em


def wordmark_geometry(font: Path) -> tuple[str, float, float, float]:
    """Outline the wordmark. Returns (path data, advance width, top, bottom)."""
    probe = (
        f'<svg xmlns="{SVG_NS}" width="400" height="64" viewBox="0 0 400 64">'
        + text(0, 0, "pillar-csi", WORD_SIZE, "#000", 700, stretch="expanded",
               spacing=WORD_SIZE * WORD_TRACKING)
        + "</svg>"
    )
    with tempfile.TemporaryDirectory() as tmp:
        inp, out = Path(tmp, "in.svg"), Path(tmp, "out.svg")
        inp.write_text(probe)
        subprocess.run([need("usvg"), *font_args(font), "--coordinates-precision", "2", str(inp), str(out)], check=True)
        paths = [p.get("d") for p in ET.parse(out).iter(f"{{{SVG_NS}}}path")]
    if not paths:
        sys.exit("usvg produced no outlines for the wordmark; check the font file")
    d = " ".join(paths)
    nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", d)]
    xs, ys = nums[0::2], nums[1::2]
    return d, max(xs), min(ys), max(ys)


def shift_d(d: str, dx: float, dy: float) -> str:
    return re.sub(
        r"(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)",
        lambda m: f"{float(m.group(1)) + dx:g} {float(m.group(2)) + dy:.2f}",
        d,
    )


def wordmark_at(x: float, baseline: float, wm: tuple, ink: str) -> str:
    d, w, _, _ = wm
    return f'<path transform="translate({x:g} {baseline:.2f})" fill="{ink}" d="{d}"/>'


# ---------------------------------------------------------------- SVG assets


def mark_svg(colors) -> str:
    return svg_doc(64, 64, shapes(MARK, colors))


def lockup_horizontal(wm, colors, ink: str) -> str:
    d, w, top, _ = wm
    shift = 32 - top / 2
    placed = shift_d(d, 64 + WORD_GAP, shift)
    width = round(64 + WORD_GAP + w + 2)
    return svg_doc(width, 64, shapes(MARK, colors) + f'\n<path fill="{ink}" d="{placed}"/>')


def lockup_stacked(wm, colors, ink: str) -> str:
    """Mark over wordmark, centered; the wordmark runs at the same 36px but the
    canvas is wider, so the pair reads as one block."""
    d, w, top, _ = wm
    mark_w = 64
    width = round(max(mark_w, w) + 16)
    mx = (width - mark_w) / 2
    baseline = 64 + 24 - top
    placed = shift_d(d, (width - w) / 2, baseline)
    body = f'<g transform="translate({mx:g} 0)">{shapes(MARK, colors)}</g>'
    body += f'\n<path fill="{ink}" d="{placed}"/>'
    return svg_doc(width, round(64 + 24 + 0 - top + 2), body)


def wordmark_only(wm, ink: str) -> str:
    d, w, top, bottom = wm
    placed = shift_d(d, 0, -top)
    return svg_doc(round(w + 2), round(-top + bottom + 2), f'<path fill="{ink}" d="{placed}"/>')


def favicon_svg() -> str:
    """White-ground colors by default; dark browser chrome swaps to the on-dark set."""
    drawn = {part for part, *_ in SMALL}
    rules = " ".join(f".pc-{p} {{ fill: {c}; }}" for p, c in SMALL_ON_DARK.items() if p in drawn)
    body = (
        f"<style>@media (prefers-color-scheme: dark) {{ {rules} }}</style>\n"
        + shapes(SMALL, SMALL_ON_LIGHT, classes=True)
    )
    return svg_doc(16, 16, body)


def tile_svg(size: int, radius_ratio: float = 3 / 16, pad_ratio: float = 0) -> str:
    """Mark on a Machine Green rounded tile. pad_ratio shrinks the mark toward the
    center for maskable icons. 16 and 48 px use the 16-unit drawing; other sizes
    use the full mark scaled to a whole-pixel fit."""
    radius = round(size * radius_ratio)
    inner = round(size * (1 - pad_ratio))
    off = (size - inner) / 2
    if inner % 16 == 0 and size in (16, 48):
        art = f'<g transform="translate({off:g} {off:g}) scale({inner / 16:g})">{shapes(SMALL, SMALL_ON_DARK)}</g>'
    else:
        # scale the 64-unit mark so every edge still lands on a whole pixel
        s = inner / 64
        art = f'<g transform="translate({off:g} {off:g}) scale({s:g})">{shapes(MARK, ON_DARK)}</g>'
    return (
        f'<svg xmlns="{SVG_NS}" width="{size}" height="{size}" viewBox="0 0 {size} {size}">'
        f'<rect width="{size}" height="{size}" rx="{radius:g}" fill="{MACHINE_GREEN}"/>{art}</svg>'
    )


def apple_touch_icon() -> str:
    # iOS rounds the corners itself, so the ground is a full square; 2x keeps edges whole.
    return (
        f'<svg xmlns="{SVG_NS}" width="180" height="180" viewBox="0 0 180 180">'
        f'<rect width="180" height="180" fill="{MACHINE_GREEN}"/>{mark(26, 26, 128)}</svg>'
    )


def avatar_svg(size: int = 500) -> str:
    """GitHub avatar: Machine Green rounded square, circle-safe mark."""
    inner = round(size * 0.62)
    off = (size - inner) / 2
    return (
        f'<svg xmlns="{SVG_NS}" width="{size}" height="{size}" viewBox="0 0 {size} {size}">'
        f'<rect width="{size}" height="{size}" rx="{round(size * 0.2):g}" fill="{MACHINE_GREEN}"/>'
        f'{mark(off, off, inner)}</svg>'
    )


