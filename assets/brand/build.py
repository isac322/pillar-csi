# ---------------------------------------------------------------- build


def outline_text(svg: str, font: Path) -> str:
    """Convert <text> to paths with usvg so the SVG renders without the font."""
    with tempfile.TemporaryDirectory() as tmp:
        inp, out = Path(tmp, "in.svg"), Path(tmp, "out.svg")
        inp.write_text(svg)
        subprocess.run([need("usvg"), *font_args(font), "--coordinates-precision", "2", str(inp), str(out)], check=True)
        return out.read_text()


def build(font: Path) -> dict[str, Path]:
    """Write every kit file and the site/public copies. Returns path -> svg for contact sheet."""
    wm = wordmark_geometry(font)
    svgd = {}

    def put(rel: str, svg: str):
        svgd[rel] = svg

    # mark/
    put("mark/mark-color-dark.svg", mark_svg(ON_DARK))
    put("mark/mark-color-light.svg", mark_svg(ON_LIGHT))
    put("mark/mark-mono-black.svg", mark_svg(MONO_BLACK))
    put("mark/mark-mono-white.svg", mark_svg(MONO_WHITE))
    put("mark/mark-mono-currentcolor.svg", mark_svg(MONO_CURRENT))

    # logo/
    put("logo/logo-horizontal-dark.svg", lockup_horizontal(wm, ON_DARK, ENAMEL_CREAM))
    put("logo/logo-horizontal-light.svg", lockup_horizontal(wm, ON_LIGHT, INK))
    put("logo/logo-horizontal-mono.svg", lockup_horizontal(wm, MONO_BLACK, "#000000"))
    put("logo/logo-stacked-dark.svg", lockup_stacked(wm, ON_DARK, ENAMEL_CREAM))
    put("logo/logo-stacked-light.svg", lockup_stacked(wm, ON_LIGHT, INK))
    put("logo/wordmark-dark.svg", wordmark_only(wm, ENAMEL_CREAM))
    put("logo/wordmark-light.svg", wordmark_only(wm, INK))

    # icon/
    put("icon/icon-app.svg", avatar_svg(500))

    # social/
    put("social/social-github.svg", card(1280, 640, "github.com/isac322/pillar-csi", wm))
    put("social/og.svg", card(1200, 630, "pillar-csi.bhyoo.com", wm))
    put("social/readme-banner-dark.svg", banner(wm, True))
    put("social/readme-banner-light.svg", banner(wm, False))

    # favicon/
    put("favicon/favicon.svg", favicon_svg())

    # palette/
    write(KIT / "palette" / "tokens.json", tokens_json())
    write(KIT / "palette" / "palette.css", palette_css())
    put("palette/palette.svg", palette_sheet())

    # write SVGs; text-bearing files go through usvg so they ship path-only
    TEXT_BEARING = {"social/", "palette/"}
    for rel, svg in svgd.items():
        if rel.split("/")[0] + "/" in TEXT_BEARING:
            svg = outline_text(svg, font)
            if GEN_NOTE not in svg:
                svg = svg.replace("<svg", f"<!-- {GEN_NOTE} -->\n<svg", 1)
            svgd[rel] = svg
        write(KIT / rel, svg)

    # rasters
    render(svgd["social/social-github.svg"], KIT / "social" / "pillar-csi-og.png", font)
    render(svgd["social/og.svg"], KIT / "social" / "og.png", font)
    render(svgd["icon/icon-app.svg"], KIT / "icon" / "avatar-github.png", font, width=500)
    render(apple_touch_icon(), KIT / "favicon" / "apple-touch-icon.png", font)
    for size in (192, 512):
        render(tile_svg(size), KIT / "favicon" / f"icon-{size}.png", font, width=size)
    render(tile_svg(512, radius_ratio=0.12, pad_ratio=0.2),
           KIT / "favicon" / "icon-maskable-512.png", font, width=512)

    pngs = []
    with tempfile.TemporaryDirectory() as tmp:
        for size in (16, 32, 48):
            out = Path(tmp, f"{size}.png")
            render(tile_svg(size), out, font, width=size)
            pngs.append((size, out.read_bytes()))
    write_ico(pngs, KIT / "favicon" / "favicon.ico")

    # site/public copies — identical files
    copies = {
        "site/public/brand/mark.svg": svgd["mark/mark-color-dark.svg"],
        "site/public/brand/mark-light.svg": svgd["mark/mark-color-light.svg"],
        "site/public/brand/logo.svg": svgd["logo/logo-horizontal-dark.svg"],
        "site/public/brand/logo-light.svg": svgd["logo/logo-horizontal-light.svg"],
        "site/public/favicon.svg": svgd["favicon/favicon.svg"],
    }
    for rel, svg in copies.items():
        write(REPO / rel, svg)
    for src, dst in (
        (KIT / "favicon" / "favicon.ico", PUBLIC / "favicon.ico"),
        (KIT / "favicon" / "apple-touch-icon.png", PUBLIC / "apple-touch-icon.png"),
        (KIT / "favicon" / "icon-192.png", PUBLIC / "icon-192.png"),
        (KIT / "favicon" / "icon-512.png", PUBLIC / "icon-512.png"),
        (KIT / "favicon" / "icon-maskable-512.png", PUBLIC / "icon-maskable-512.png"),
        (KIT / "social" / "og.png", PUBLIC / "og.png"),
        (KIT / "social" / "pillar-csi-og.png", DOCS_OG),
    ):
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    write(PUBLIC / "site.webmanifest", webmanifest_json())

    return svgd


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font-file", type=Path, help="local Archivo[wdth,wght].ttf instead of the pinned download")
    args = ap.parse_args()
    font = fetch_font(args.font_file)
    build(font)
    return 0


if __name__ == "__main__":
    sys.exit(main())
